								<h1>Inspeção/Fiscalização de Fabricação</h1>
							<p>Os serviços de Inspeção de Fabricação, têm como principal objetivo minimizar a possibilidade de ocorrência de defeitos nos equipamentos decorrentes de erros de projetos ou deficiência nos processos.</p>
							<p>Descrevemos abaixo as principais atividades a serem executadas:</p>
						</section>

						<section>
							<h3>Auditoria de Fornecedores</h3>
							<p>Visita aos fornecedores de equipamentos e materiais para verificarmos as instalações, procedimentos de fabricação, qualificação de pessoal, sistema e exames para controle de qualidade.</p>
							<h3>Verificação do Projeto Mecânico</h3>
							<p>A natureza da atividade de projeto por si só demanda sua verificação. Através de nossa engenharia fornecemos o serviço de verificação do projeto mecânico, do equipamento a ser fabricado para contribuir na minimização de erros, assim como sugerir melhorias que possam ser implementadas a baixo custo, com retorno nas atividades futuras de inspeção e manutenção.</p>
							<h3>Comentários dos Planos de Fabricação e Inspeção</h3>
							<p>Antes do início da fabricação, nossa equipe verifica os planos e procedimentos de fabricação e de controle de qualidade.</p>
							<p>São feitos comentários e sugestões para minimizar o defeitos durante os processos de fabricação, tais como conformação e soldagem.</p>
							<p>De posse das informações, são determinados os pontos de verificação para Fiscalização da Fabricação.</p>
							<h3>Inspeções de Fabricação</h3>
							<p>As inspeções definidas no plano de inspeções (PIT) são executadas por inspetores sob supervisão da engenharia.</p>
							<p>Nas visitas são verificados tanto os aspectos técnicos, como também o cumprimento dos prazos.</p>
							<p>Nossa postura é detectar as não-conformidades, contribuir na avaliação e proposição de possíveis soluções, considerando os aspectos de custos, prazos e melhores práticas de engenharia.</p>


